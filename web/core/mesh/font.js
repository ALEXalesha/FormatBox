// Строки глифа 0/1 или null, если такого знака нет (пробел - пустой глиф)
export function glyph(ch) {
  if (ch === ' ') return Array.from({ length: GLYPH_H }, () => [0, 0, 0]);
  const g = L[ch] ?? L[ch.toUpperCase()];
  return g ? g.split(' ').map((row) => [...row].map(Number)) : null;
}

export function hasGlyph(ch) {
  return glyph(ch) !== null;
}
